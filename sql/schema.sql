-- Reference schema for a NEW database only.
-- For the existing pgAdmin database, run migrations/001_product_setup.sql instead.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    source_uri TEXT NOT NULL,
    mime_type TEXT NOT NULL DEFAULT 'application/pdf',
    content_hash TEXT UNIQUE,
    status TEXT NOT NULL DEFAULT 'ready',
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    chunk_index INT NOT NULL CHECK (chunk_index >= 0),
    extraction_method TEXT NOT NULL DEFAULT 'pymupdf',
    chunking_strategy TEXT NOT NULL DEFAULT 'section',
    content TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    token_count INT CHECK (token_count IS NULL OR token_count >= 0),
    embedding VECTOR(768) NOT NULL,
    UNIQUE (document_id, extraction_method, chunking_strategy, chunk_index)
);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oidc_subject TEXT UNIQUE,
    email TEXT NOT NULL,
    display_name TEXT,
    role TEXT NOT NULL DEFAULT 'recruiter' CHECK (role IN ('admin', 'recruiter')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login TIMESTAMPTZ
);
CREATE UNIQUE INDEX ux_app_users_email_lower ON app_users(LOWER(email));

CREATE TABLE ingestion_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    document_id BIGINT REFERENCES documents(id) ON DELETE SET NULL,
    file_name TEXT NOT NULL,
    content_hash TEXT,
    action TEXT NOT NULL CHECK (action IN ('upload', 'replace', 'delete')),
    status TEXT NOT NULL CHECK (status IN ('accepted', 'rejected', 'processing', 'succeeded', 'failed', 'duplicate')),
    reasons JSONB NOT NULL DEFAULT '[]'::jsonb,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_chunks_document_id ON chunks(document_id);
CREATE INDEX idx_chunks_metadata_gin ON chunks USING GIN(metadata);
CREATE INDEX idx_chunks_embedding_hnsw ON chunks USING hnsw (embedding vector_cosine_ops);
CREATE INDEX idx_documents_job_fields_gin ON documents USING GIN ((metadata->'job_fields'));
