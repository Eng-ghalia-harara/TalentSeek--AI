-- One-time product setup migration for the EXISTING database.
-- The previous migration already created documents/chunks and changed embedding to VECTOR(768).
-- This migration is non-destructive: it does not delete documents or chunks.
BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oidc_subject TEXT UNIQUE,
    email TEXT NOT NULL,
    display_name TEXT,
    role TEXT NOT NULL DEFAULT 'recruiter'
        CHECK (role IN ('admin', 'recruiter')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_app_users_email_lower
    ON app_users (LOWER(email));

ALTER TABLE documents
    ADD COLUMN IF NOT EXISTS created_by_user_id BIGINT REFERENCES app_users(id),
    ADD COLUMN IF NOT EXISTS updated_by_user_id BIGINT REFERENCES app_users(id);

CREATE TABLE IF NOT EXISTS ingestion_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    document_id BIGINT REFERENCES documents(id) ON DELETE SET NULL,
    file_name TEXT NOT NULL,
    content_hash TEXT,
    action TEXT NOT NULL CHECK (action IN ('upload', 'replace', 'delete')),
    status TEXT NOT NULL CHECK (status IN ('accepted', 'rejected', 'processing', 'succeeded', 'failed', 'duplicate')),
    reasons JSONB NOT NULL DEFAULT '[]'::jsonb,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ingestion_events_created_at
    ON ingestion_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ingestion_events_user_id
    ON ingestion_events(user_id);
CREATE INDEX IF NOT EXISTS idx_documents_status
    ON documents(status);
CREATE INDEX IF NOT EXISTS idx_chunks_document_id
    ON chunks(document_id);
CREATE INDEX IF NOT EXISTS idx_chunks_embedding_hnsw
    ON chunks USING hnsw (embedding vector_cosine_ops);
CREATE INDEX IF NOT EXISTS idx_chunks_metadata_gin
    ON chunks USING GIN(metadata);

-- Prevent storing the exact same file twice in the current shared CV set.
CREATE UNIQUE INDEX IF NOT EXISTS ux_documents_content_hash
    ON documents(content_hash)
    WHERE content_hash IS NOT NULL AND content_hash <> '';

COMMIT;
